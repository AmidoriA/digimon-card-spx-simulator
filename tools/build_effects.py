"""Export the battle effect scripts for the web game.

Usage (venv python):  build_effects.py <extracted_dir> <web_dir>

Writes web/js/data/effects.js: every script of B/CBTL_EFF.ARC as a list of commands
(see effscript.py for the command set; jump targets are command indices).
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import effscript  # noqa: E402


def main():
    ext, web = sys.argv[1], sys.argv[2]
    scripts = effscript.load(ext)
    path = os.path.join(web, "js", "data", "effects.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_effects.py from B/CBTL_EFF.ARC. Do not edit.\n")
        f.write("window.DDCB_EFFECTS = [\n")
        f.write(",\n".join(json.dumps(s, separators=(",", ":")) for s in scripts))
        f.write("\n];\n")
    print("scripts:", len(scripts), "commands:", sum(len(s) for s in scripts), "bytes:", os.path.getsize(path))


if __name__ == "__main__":
    main()
